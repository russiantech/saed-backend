import os
import django

os.environ.setdefault("DJANGO_SETTINGS_MODULE", "config.settings")
django.setup()

from django.db import connection
from django.db.migrations.loader import MigrationLoader

TARGET = ("saed", "0002_unified_lessons_payments_schema")

print("\nChecking production database against SAED migration state...\n")

loader = MigrationLoader(connection)
state = loader.project_state([TARGET])
models = [
    model for model in state.apps.get_models()
    if model._meta.app_label == "saed"
]

existing_tables = set(connection.introspection.table_names())
missing_tables = []
repairs = []

with connection.cursor() as cursor:
    for model in models:
        table = model._meta.db_table

        if table not in existing_tables:
            missing_tables.append(table)
            continue

        existing_columns = {
            column.name
            for column in connection.introspection.get_table_description(
                cursor, table
            )
        }

        for field in model._meta.local_concrete_fields:
            column = field.column

            if column not in existing_columns:
                repairs.append((model, field))


if missing_tables:
    print("STOP: Required tables are missing:")
    for table in missing_tables:
        print("  MISSING TABLE:", table)

    print("\nNo changes were made. Missing tables need separate reconciliation.")
    raise SystemExit(1)


if not repairs:
    print("All expected columns from migrations 0001 and 0002 exist.")
else:
    print("Missing columns identified:")
    for model, field in repairs:
        print(f"  {model._meta.db_table}.{field.column}")

    print("\nApplying missing columns using Django schema editor...\n")

    with connection.schema_editor() as editor:
        for model, field in repairs:
            print(f"Adding {model._meta.db_table}.{field.column}")
            editor.add_field(model, field)

    print("\nAll missing columns added successfully.")


print("\nSchema reconciliation completed.")
