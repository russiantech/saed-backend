"""Render the OpenAPI spec as a readable Markdown reference."""


def _schema_rows(schema, prefix=""):
    rows = []
    req = set(schema.get("required", []))
    for name, s in (schema.get("properties") or {}).items():
        t = s.get("type") or ("ref" if "$ref" in s else "any")
        if isinstance(t, list):
            t = " \\| ".join(t)
        if s.get("format"):
            t += f" ({s['format']})"
        if "$ref" in s:
            t = s["$ref"].rsplit("/", 1)[-1]
        rows.append(f"| `{prefix}{name}` | {t} | {'yes' if name in req else ''} | {s.get('description', '')} |")
    return rows


def render_markdown(spec):
    info = spec["info"]
    out = [f"# {info['title']} — v{info['version']}", "", "> Generated by `python manage.py export_openapi`. "
           "Do not edit by hand. Live docs: `/api/docs/` (Swagger UI), `/api/redoc/`, `/api/openapi.json`.", "",
           info["description"], ""]
    by_tag = {}
    for path, item in spec["paths"].items():
        for method, op in item.items():
            by_tag.setdefault(op["tags"][0], []).append((path, method, op))
    out += ["## Contents", ""] + [f"- [{t['name']}](#{t['name'].lower().replace(' ', '-')}) — {t['description']}" for t in spec["tags"] if t["name"] in by_tag] + [""]
    for t in spec["tags"]:
        ops = by_tag.get(t["name"])
        if not ops:
            continue
        out += [f"## {t['name']}", "", t["description"], ""]
        for path, method, op in ops:
            out += [f"### `{method.upper()} {path}`", "", f"**{op['summary']}**", "", op["description"], ""]
            if op.get("x-csrf"):
                out += [f"_{op['x-csrf']}_", ""]
            params = op.get("parameters", [])
            if params:
                out += ["| Parameter | In | Type | Description |", "|---|---|---|---|"]
                out += [f"| `{p['name']}` | {p['in']} | {p['schema'].get('type')} | {p.get('description', '')} |" for p in params]
                out.append("")
            body = op.get("requestBody")
            if body:
                for ctype, c in body["content"].items():
                    rows = _schema_rows(c["schema"])
                    out += [f"Request body (`{ctype}`):", ""]
                    if rows:
                        out += ["| Field | Type | Required | Description |", "|---|---|---|---|"] + rows + [""]
                    else:
                        out += ["Free-form JSON object.", ""]
            out += ["Responses: " + ", ".join(f"`{c}`" for c in op["responses"]), ""]
    out += ["## Schemas", ""]
    for name, s in spec["components"]["schemas"].items():
        out += [f"### {name}", "", "| Field | Type | Required | Description |", "|---|---|---|---|"] + _schema_rows(s) + [""]
    return "\n".join(out) + "\n"
